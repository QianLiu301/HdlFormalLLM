def not_executable(key: Optional[str]) -> Optional[str]:
    """Why the web testbench does not do what a canonical step says, or None."""
    st = step_by_key(key)
    return st.get('why') if st and st.get('executable') is False else None


# The tag of a register-file scenario decides what the testbench runs, whatever
# its steps say: a @read scenario only reads, so a write step in it never happens.
_RF_RUN_BY = {'RF.A.WRITE': {'WRITE', 'WRITE_READ'}, 'RF.A.RESET': {'RESET'}}
TAG_SKIPS_STEP = "the scenario's tag makes the testbench leave this step out"


def runs_by_tag(key: Optional[str]) -> bool:
    return key in _RF_RUN_BY


def not_run(key: Optional[str], operations) -> Optional[str]:
    """Why a step did not happen in a scenario the testbench ran as these operations."""
    wanted = _RF_RUN_BY.get(key)
    return TAG_SKIPS_STEP if wanted and operations and not (wanted & set(operations)) else None


_RF_SAME_CYCLE = re.compile(r'\bsame (?:clock )?cycle\b|\bbeing written\b|\bduring (?:a |the )?write\b'
                            r'|\bwhile (?:it is )?(?:being )?writ', re.I)


def cannot_test(module_type: Optional[str], text: Optional[str]) -> Optional[str]:
    """Why no scenario can show this requirement on the web testbench, or None.

    Its rows run one after another, so a passing row says nothing about a read in
    the cycle of a write, whichever scenario the model linked to the requirement."""
    if module_type == 'regfile' and _RF_SAME_CYCLE.search(text or ''):
        return step_by_key('RF.A.SAME_CYCLE')['why']
    if module_type in ('alu', 'alu_comb') and _ALU_RESET.search(text or ''):
        return ALU_RESET_WHY
    return None


# The ALU testbench resets once, before the first example, and no ALU step asserts
# reset later, so what reset does to the outputs is never observed (D48).
_ALU_RESET = re.compile(r'\b(?:reset|rst)\b', re.I)
ALU_RESET_WHY = ('the ALU testbench applies reset only once, before the first example, '
                 'and no scenario step can apply it again')


def step_by_key(key: Optional[str]) -> Optional[Dict]:
    for lib in LIBRARIES.values():
        for st in lib['steps']:
            if st['key'] == key:
                return st
    return None


def value_param(key: Optional[str], names) -> Optional[str]:
    """Which parameter of a mapped step holds the port value (the first one
    unless the library says otherwise, e.g. DATA of 'write <DATA> to <ADDR>')."""
    st = step_by_key(key)
    names = list(names or [])
    if st and st.get('value') in names:
        return st['value']
    return names[0] if names else None


def library_for(module_type: Optional[str]) -> Optional[Dict]:
    return LIBRARIES.get((module_type or '').strip())


def map_step(module_type: str, text: str) -> Optional[Tuple[Dict, Dict]]:
    """(canonical step, params) for one surface step, or None if no rule matches."""
    lib = library_for(module_type)
    if not lib:
        return None
    s = re.sub(r'\s+', ' ', text.strip())
    # models annotate steps with the requirements they serve: "... (REQ-7, REQ-8)"
    s = re.sub(r'\s*\((?:REQ-\d+[,;\s]*)+\)$', '', s, flags=re.I)
    for step in lib['steps']:
        for rx in step['patterns']:
            m = rx.match(s)
            if m:
                params = {}
                for k, v in m.groupdict().items():
                    if v is None:
                        continue
                    params[k] = {'col': v[1:-1]} if v.startswith('<') else {'lit': v}
                return step, params
    return None


def resolve(params: Dict, row_vals: Optional[Dict]) -> Dict[str, Optional[str]]:
    """Parameter values of a mapped step for one Examples row."""
    out = {}
    for k, p in (params or {}).items():
        out[k] = row_vals.get(p['col']) if 'col' in p else p.get('lit')
        if 'col' in p and row_vals is not None and out[k] is None:
            # header case differs between models (Expected_Result / expected_result)
            low = {kk.lower(): vv for kk, vv in row_vals.items()}
            out[k] = low.get(p['col'].lower())
    return out


def instantiate(text: str, row_vals: Optional[Dict]) -> str:
    """Step text with <Col> placeholders replaced by the row's values."""
    if not row_vals:
        return text
    low = {k.lower(): v for k, v in row_vals.items()}
    return re.sub(r'<([^>]+)>', lambda m: str(row_vals.get(m.group(1), low.get(m.group(1).lower(),
                                                                               m.group(0)))), text)


def to_int(v, width: Optional[int] = None) -> Optional[int]:
    """Examples values as the testbench sees them: True/False -> 1/0, masked."""
    if v is None:
        return None
    s = str(v).strip()
    if s.lower() in ('true', 'false'):
        x = int(s.lower() == 'true')
    else:
        try:
            x = int(s, 0)
        except ValueError:
            return None
    return x & ((1 << width) - 1) if width else x


def apply_rule(module_type: str, op: Optional[str], a, b, width: int) -> Optional[int]:
    lib = library_for(module_type)
    rule = (lib or {}).get('rules', {}).get((op or '').upper())
    ai, bi = to_int(a, width), to_int(b, width)
    if rule is None or rule.get('fn') is None or ai is None or bi is None:
        return None
    return rule['fn'](ai, bi, width)


def _signed_overflow(op, a, b, w):
    op = (op or '').upper()
    if op not in ('ADD', 'SUB'):
        return None
    r = ((a + b) if op == 'ADD' else (a - b)) % (1 << w)
    sa, sb, sr = a >> (w - 1), b >> (w - 1), r >> (w - 1)
    return int(sa == sb and sr != sa) if op == 'ADD' else int(sa != sb and sr != sa)


def _carry(op, a, b, w):
    op = (op or '').upper()
    if op == 'ADD':
        return int(a + b >= 1 << w)
    if op == 'SUB':
        return int(a < b)
    return None


# The two meanings "overflow" has in practice. Which one is the rule for a run
# is a specification choice: the Step-0 answer if there is one, otherwise the
# tool's design template (signed). The other one is only used to say what a
# specification seems to mean when it contradicts the rule.
OVERFLOW_DEFINITIONS = {
    'signed': {'name': 'signed overflow', 'expr': 'overflow == signed overflow of ADD/SUB',
               'text': 'the overflow flag is 1 when ADD or SUB overflows as a signed operation',
               'fn': _signed_overflow},
    'carry': {'name': 'unsigned carry/borrow', 'expr': 'overflow == carry of ADD / borrow of SUB',
              'text': 'the overflow flag is 1 when ADD carries out of the top bit or SUB borrows (A < B)',
              'short': 'ADD: A + B ≥ 2^W; SUB: A < B', 'fn': _carry},
}
OVERFLOW_DEFINITIONS['signed']['short'] = 'ADD/SUB result outside the signed W-bit range'
DEFAULT_OVERFLOW_MODE = 'signed'          # prompts/duv_alu v2/v3 compute signed overflow


def overflow_mode_from_answer(answer: Optional[str]) -> Optional[str]:
    """Map the Step-0 answer to a definition; None for a custom answer."""
    from src import requirements_store as R
    return {R.OVERFLOW_SIGNED: 'signed', R.OVERFLOW_CARRY: 'carry'}.get((answer or '').strip())


def flag_rule(module_type: str, port: str, overflow_mode: Optional[str] = DEFAULT_OVERFLOW_MODE,
              basis: Optional[str] = None) -> Optional[Dict]:
    """{expr, text, basis} of the rule for a flag, or None (no library / custom answer)."""
    lib = library_for(module_type)
    if not lib:
        return None
    if port == 'overflow':
        d = OVERFLOW_DEFINITIONS.get(overflow_mode or '')
        if d is None:
            return None
        return {'expr': d['expr'], 'text': d['text'], 'name': d['name'],
                'basis': basis or "the tool's design template, prompts/duv_alu"}
    r = lib['flags'].get(port)
    return {**r, 'basis': 'definition of the flag'} if r else None


def flag_value(module_type: str, port: str, op: Optional[str], a, b, width: int,
               overflow_mode: Optional[str] = DEFAULT_OVERFLOW_MODE) -> Optional[int]:
    """What the flag rules give for a flag the testbench does not compare.
    None when the rule does not define the flag for this operation (e.g.
    overflow of AND: a specification choice, not a fact) or no rule applies."""
    res = apply_rule(module_type, op, a, b, width)
    if res is None:
        return None
    if port == 'zero':
        return int(res == 0)
    if port == 'negative':
        return (res >> (width - 1)) & 1
    if port == 'overflow':
        d = OVERFLOW_DEFINITIONS.get(overflow_mode or '')
        return d['fn'](op, to_int(a, width), to_int(b, width), width) if d else None
    return None


def flag_alternatives(module_type: str, port: str, op, a, b, width: int,
                      overflow_mode: Optional[str] = DEFAULT_OVERFLOW_MODE) -> List[Dict]:
    """[{name, text, value}] for the other known meanings of a flag."""
    if not library_for(module_type) or port != 'overflow':
        return []
    ai, bi = to_int(a, width), to_int(b, width)
    if ai is None or bi is None:
        return []
    out = []
    for mode, d in OVERFLOW_DEFINITIONS.items():
        if mode == overflow_mode:
            continue
        v = d['fn'](op, ai, bi, width)
        if v is not None:
            out.append({'name': d['name'], 'text': d['short'], 'value': v})
    return out


def alternative_by_name(name: str) -> Optional[Dict]:
    return next(({'name': d['name'], 'text': d['short']} for d in OVERFLOW_DEFINITIONS.values()
                 if d['name'] == name), None)


# ----------------------------------------------------------------- ALU mix-ups
# What a design or a scenario may have done instead of the rule. Like
# FLAG_ALTERNATIVES these only describe a result, they never judge one: the
# verdict comes from verdict.classify alone. A mix-up is reported only when it
# reproduces every example of the operation, so the cause on a card is proven by
# the run itself, and "the cause is unknown" stays the answer otherwise.
_shift = lambda b, w: b & (w - 1)
ALU_MIXUPS = {
    'SLT': {'fn': lambda a, b, w: int(a < b), 'as': 'SLTU',
            'says': 'compares SLT operands as unsigned numbers',
            'fix': 'the comparison needs $signed on both operands'},
    'SLTU': {'fn': lambda a, b, w: int(_signed(a, w) < _signed(b, w)), 'as': 'SLT',
             'says': 'compares SLTU operands as signed numbers',
             'fix': 'the comparison must not use $signed'},
    'SRA': {'fn': lambda a, b, w: a >> _shift(b, w), 'as': 'SRL',
            'says': 'shifts SRA with zeros instead of copying the sign bit',
            'fix': 'the operand needs $signed for >>> to copy the sign bit'},
    'SRL': {'fn': lambda a, b, w: (_signed(a, w) >> _shift(b, w)) % (1 << w), 'as': 'SRA',
            'says': 'shifts SRL with the sign bit instead of zeros',
            'fix': 'SRL must fill with zeros'},
    'ADD': {'fn': lambda a, b, w: (a - b) % (1 << w), 'as': 'SUB',
            'says': 'subtracts instead of adding', 'fix': 'ADD must add'},
    'SUB': {'fn': lambda a, b, w: (a + b) % (1 << w), 'as': 'ADD',
            'says': 'adds instead of subtracting', 'fix': 'SUB must subtract'},
}
# A shifter that loses one bit of the shift amount, such as a barrel shifter with
# a stage left out: shifting by 31 moves 15 positions when bit 4 is ignored.
SHIFTS = {'SLL': lambda a, s, w: (a << s) % (1 << w),
          'SRL': lambda a, s, w: a >> s,
          'SRA': lambda a, s, w: (_signed(a, w) >> s) % (1 << w)}
# Values an operation treats as signed; a reader should see them that way.
SIGNED_OPERANDS = {'SLT': ('a', 'b'), 'SRA': ('a', 'result')}
ALU_WORKING = {'SLT': lambda a, b, w: f"{_signed(a, w)} < {_signed(b, w)} is {'true' if _signed(a, w) < _signed(b, w) else 'false'}",
               'SLTU': lambda a, b, w: f"{a} < {b} is {'true' if a < b else 'false'}",
               'SRA': lambda a, b, w: f"{_signed(a, w)} >> {_shift(b, w)} = {_signed(a, w) >> _shift(b, w)}"}


def signed_value(op: Optional[str], operand: str, value, width: Optional[int]) -> Optional[int]:
    """The negative number a reader should see for this operand, else None."""
    if width and isinstance(value, int) and operand in SIGNED_OPERANDS.get((op or '').upper(), ()) \
            and value >= 1 << (width - 1):
        return _signed(value, width)
    return None


def alu_working(op: Optional[str], a, b, width: Optional[int]) -> Optional[str]:
    fn = ALU_WORKING.get((op or '').upper())
    return fn(a, b, width) if fn and width and isinstance(a, int) and isinstance(b, int) else None


def alu_mixup(op: Optional[str], rows: List[Tuple[int, int, int]], width: Optional[int]) -> Optional[Dict]:
    """The mix-up that reproduces every (a, b, value) of an operation and differs
    from the rule at least once, with the number of rows it explains."""
    key = (op or '').upper()
    mix, rule = ALU_MIXUPS.get(key), (library_for('alu') or {}).get('rules', {}).get(key)
    if not rule or not rows or not width:
        return None
    if all(rule['fn'](a, b, width) == v for a, b, v in rows):
        return None
    if mix and all(mix['fn'](a, b, width) == v for a, b, v in rows):
        return {'op': key, 'says': mix['says'], 'fix': mix['fix'], 'rows': len(rows)}
    bits = [k for k in _shift_bits(key, width)
            if all(_shift_without(key, a, b, width, k) == v for a, b, v in rows)]
    if len(bits) != 1:                 # several bits fit: the run does not say which one
        return None
    return {'op': key, 'bit': bits[0], 'says': f'ignores bit {bits[0]} of the shift amount',
            'fix': f'bit {bits[0]} of B must shift by {1 << bits[0]} more positions', 'rows': len(rows)}


def _shift_bits(op: str, width: int) -> List[int]:
    return list(range(width.bit_length() - 1)) if op in SHIFTS and width & (width - 1) == 0 else []


def _shift_without(op: str, a: int, b: int, width: int, bit: int) -> int:
    return SHIFTS[op](a, _shift(b, width) & ~(1 << bit), width)


def alu_has_cause(op: Optional[str]) -> bool:
    return (op or '').upper() in ALU_MIXUPS or (op or '').upper() in SHIFTS


def alu_shift_hidden(op: str, rows: List[Tuple[int, int, int]], bit: int, width: int) -> bool:
    """True when every example of a shift passes and none could show the lost bit:
    its pass says nothing about that fault."""
    return bool(rows) and all(SHIFTS[op](a, _shift(b, width), width) == v
                              and _shift_without(op, a, b, width, bit) == v for a, b, v in rows)


def alu_shift_witness(op: str, bit: int, width: int) -> Tuple[int, int, int, int]:
    """(a, b, correct, value with the fault) of an example that shows the lost bit."""
    a, b = (1 if op == 'SLL' else 1 << (width - 1)), 1 << bit
    return a, b, SHIFTS[op](a, b, width), _shift_without(op, a, b, width, bit)


def alu_swap_partner(op: Optional[str]) -> Optional[str]:
    return (ALU_MIXUPS.get((op or '').upper()) or {}).get('as')


def alu_mixup_value(op: Optional[str], a: int, b: int, width: int, cause: Optional[Dict] = None) -> Optional[int]:
    if cause and 'bit' in cause:
        return _shift_without(cause['op'], a, b, width, cause['bit'])
    mix = ALU_MIXUPS.get((op or '').upper())
    return mix['fn'](a, b, width) if mix else None
