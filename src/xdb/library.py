"""
Canonical-step and rule library (design doc §4, D19). Written by hand,
provenance `human`; nothing here is generated by a model.

Canonical steps are the alphabet Σ of BDX: one entry per meaning, whatever
wording a model used. Each entry has
    key        stable id, e.g. ALU.P.A
    role       context | action | outcome  (Given / When / Then)
    template   display form, e.g. "operand A = <A>"
    patterns   regexes over the surface text; named groups are parameters
    port       DUV port the step talks about (None for configuration)
    expr       predicate over ports, SV-compatible, {X} = parameter X
A parameter written as <Col> in the step refers to an Examples column; the
mapping stores it as {"col": "Col"}, a literal as {"lit": "5"}.

Rules give the operation semantics the explanations quote ("SUB computes
A - B modulo 2^W"). All text is English. `fn` is an independent implementation checked against
TestbenchGenerator._reference_result in the tests.
"""

