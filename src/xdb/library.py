def _signed(x: int, w: int) -> int:
    return x - (1 << w) if x >> (w - 1) else x


def _rule(op, expr, text, fn):
    return {'op': op, 'expr': expr, 'text': text, 'fn': fn}


# fn(a, b, w) with a, b already masked to w bits; result masked to w bits
ALU_RULES: Dict[str, Dict] = {r['op']: r for r in [
    _rule('ADD', 'result == (a + b) % 2**W', 'ADD computes A + B modulo 2^W', lambda a, b, w: (a + b) % (1 << w)),
    _rule('SUB', 'result == (a - b) % 2**W', 'SUB computes A − B modulo 2^W', lambda a, b, w: (a - b) % (1 << w)),
    _rule('AND', 'result == a & b', 'AND computes the bitwise AND of A and B', lambda a, b, w: a & b),
    _rule('OR', 'result == a | b', 'OR computes the bitwise OR of A and B', lambda a, b, w: a | b),
    _rule('XOR', 'result == a ^ b', 'XOR computes the bitwise XOR of A and B', lambda a, b, w: a ^ b),
    _rule('SLL', 'result == (a << b[log2 W-1:0]) % 2**W',
          'SLL shifts A left by the low log2(W) bits of B',
          lambda a, b, w: (a << (b & (w - 1))) % (1 << w)),
    _rule('SRL', 'result == a >> b[log2 W-1:0]',
          'SRL shifts A right by the low log2(W) bits of B, filling with zeros',
          lambda a, b, w: a >> (b & (w - 1))),
    _rule('SRA', 'result == $signed(a) >>> b[log2 W-1:0]',
          'SRA shifts A right by the low log2(W) bits of B, copying the sign bit',
          lambda a, b, w: (_signed(a, w) >> (b & (w - 1))) % (1 << w)),
    _rule('SLT', 'result == ($signed(a) < $signed(b))',
          'SLT is 1 when A < B as signed numbers, else 0',
          lambda a, b, w: int(_signed(a, w) < _signed(b, w))),
    _rule('SLTU', 'result == (a < b)',
          'SLTU is 1 when A < B as unsigned numbers, else 0',
          lambda a, b, w: int(a < b)),
]}

FLAG_RULES = {
    'zero': {'expr': 'zero == (result == 0)', 'text': 'the zero flag is 1 exactly when the result is 0'},
    'negative': {'expr': 'negative == result[W-1]', 'text': 'the negative flag is the top bit of the result'},
    # overflow: one of OVERFLOW_DEFINITIONS, chosen per session (flag_rule)
}

LIBRARIES = {'alu': {'steps': ALU_STEPS, 'rules': ALU_RULES, 'flags': FLAG_RULES}}
LIBRARIES['alu_comb'] = LIBRARIES['alu']


def library_for(module_type: Optional[str]) -> Optional[Dict]:
    return LIBRARIES.get((module_type or '').strip())


def map_step(module_type: str, text: str) -> Optional[Tuple[Dict, Dict]]:
    """(canonical step, params) for one surface step, or None if no rule matches."""
    lib = library_for(module_type)
    if not lib:
        return None
    s = re.sub(r'\s+', ' ', text.strip())
    for step in lib['steps']:
        for rx in step['patterns']:
            m = rx.match(s)
            if m:
                params = {}
                for k, v in m.groupdict().items():
                    if v is None:
                        continue
                    params[k] = {'col': v[1:-1]} if v.startswith('<') else {'lit': v}
                return step, params
    return None


def resolve(params: Dict, row_vals: Optional[Dict]) -> Dict[str, Optional[str]]:
    """Parameter values of a mapped step for one Examples row."""
    out = {}
    for k, p in (params or {}).items():
        out[k] = row_vals.get(p['col']) if 'col' in p else p.get('lit')
        if 'col' in p and row_vals is not None and out[k] is None:
            # header case differs between models (Expected_Result / expected_result)
            low = {kk.lower(): vv for kk, vv in row_vals.items()}
            out[k] = low.get(p['col'].lower())
    return out


def instantiate(text: str, row_vals: Optional[Dict]) -> str:
    """Step text with <Col> placeholders replaced by the row's values."""
    if not row_vals:
        return text
    low = {k.lower(): v for k, v in row_vals.items()}
    return re.sub(r'<([^>]+)>', lambda m: str(row_vals.get(m.group(1), low.get(m.group(1).lower(),
                                                                               m.group(0)))), text)


def to_int(v, width: Optional[int] = None) -> Optional[int]:
    """Examples values as the testbench sees them: True/False -> 1/0, masked."""
    if v is None:
        return None
    s = str(v).strip()
    if s.lower() in ('true', 'false'):
        x = int(s.lower() == 'true')
    else:
        try:
            x = int(s, 0)
        except ValueError:
            return None
    return x & ((1 << width) - 1) if width else x


def apply_rule(module_type: str, op: Optional[str], a, b, width: int) -> Optional[int]:
    lib = library_for(module_type)
    rule = (lib or {}).get('rules', {}).get((op or '').upper())
    ai, bi = to_int(a, width), to_int(b, width)
    if rule is None or ai is None or bi is None:
        return None
    return rule['fn'](ai, bi, width)


def _signed_overflow(op, a, b, w):
    op = (op or '').upper()
    if op not in ('ADD', 'SUB'):
        return None
    r = ((a + b) if op == 'ADD' else (a - b)) % (1 << w)
    sa, sb, sr = a >> (w - 1), b >> (w - 1), r >> (w - 1)
    return int(sa == sb and sr != sa) if op == 'ADD' else int(sa != sb and sr != sa)


def _carry(op, a, b, w):
    op = (op or '').upper()
    if op == 'ADD':
        return int(a + b >= 1 << w)
    if op == 'SUB':
        return int(a < b)
    return None


# The two meanings "overflow" has in practice. Which one is the rule for a run
# is a specification choice: the Step-0 answer if there is one, otherwise the
# tool's design template (signed). The other one is only used to say what a
# specification seems to mean when it contradicts the rule.
OVERFLOW_DEFINITIONS = {
    'signed': {'name': 'signed overflow', 'expr': 'overflow == signed overflow of ADD/SUB',
               'text': 'the overflow flag is 1 when ADD or SUB overflows as a signed operation',
               'fn': _signed_overflow},
    'carry': {'name': 'unsigned carry/borrow', 'expr': 'overflow == carry of ADD / borrow of SUB',
              'text': 'the overflow flag is 1 when ADD carries out of the top bit or SUB borrows (A < B)',
              'short': 'ADD: A + B ≥ 2^W; SUB: A < B', 'fn': _carry},
}
OVERFLOW_DEFINITIONS['signed']['short'] = 'ADD/SUB result outside the signed W-bit range'
DEFAULT_OVERFLOW_MODE = 'signed'          # prompts/duv_alu v2/v3 compute signed overflow


def overflow_mode_from_answer(answer: Optional[str]) -> Optional[str]:
    """Map the Step-0 answer to a definition; None for a custom answer."""
    from src import requirements_store as R
    return {R.OVERFLOW_SIGNED: 'signed', R.OVERFLOW_CARRY: 'carry'}.get((answer or '').strip())


def flag_rule(module_type: str, port: str, overflow_mode: Optional[str] = DEFAULT_OVERFLOW_MODE,
              basis: Optional[str] = None) -> Optional[Dict]:
    """{expr, text, basis} of the rule for a flag, or None (no library / custom answer)."""
    lib = library_for(module_type)
    if not lib:
        return None
    if port == 'overflow':
        d = OVERFLOW_DEFINITIONS.get(overflow_mode or '')
        if d is None:
            return None
        return {'expr': d['expr'], 'text': d['text'], 'name': d['name'],
                'basis': basis or "the tool's design template, prompts/duv_alu"}
    r = lib['flags'].get(port)
    return {**r, 'basis': 'definition of the flag'} if r else None


def flag_value(module_type: str, port: str, op: Optional[str], a, b, width: int,
               overflow_mode: Optional[str] = DEFAULT_OVERFLOW_MODE) -> Optional[int]:
    """What the flag rules give for a flag the testbench does not compare.
    None when the rule does not define the flag for this operation (e.g.
    overflow of AND: a specification choice, not a fact) or no rule applies."""
    res = apply_rule(module_type, op, a, b, width)
    if res is None:
        return None
    if port == 'zero':
        return int(res == 0)
    if port == 'negative':
        return (res >> (width - 1)) & 1
    if port == 'overflow':
        d = OVERFLOW_DEFINITIONS.get(overflow_mode or '')
        return d['fn'](op, to_int(a, width), to_int(b, width), width) if d else None
    return None


def flag_alternatives(module_type: str, port: str, op, a, b, width: int,
                      overflow_mode: Optional[str] = DEFAULT_OVERFLOW_MODE) -> List[Dict]:
    """[{name, text, value}] for the other known meanings of a flag."""
    if not library_for(module_type) or port != 'overflow':
        return []
    ai, bi = to_int(a, width), to_int(b, width)
    if ai is None or bi is None:
        return []
    out = []
    for mode, d in OVERFLOW_DEFINITIONS.items():
        if mode == overflow_mode:
            continue
        v = d['fn'](op, ai, bi, width)
        if v is not None:
            out.append({'name': d['name'], 'text': d['short'], 'value': v})
    return out


def alternative_by_name(name: str) -> Optional[Dict]:
    return next(({'name': d['name'], 'text': d['short']} for d in OVERFLOW_DEFINITIONS.values()
                 if d['name'] == name), None)
