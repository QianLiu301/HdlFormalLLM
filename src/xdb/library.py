_VAL = r'(?P<{n}><[^>]+>|[-+]?\w+)'


def _p(rx: str) -> re.Pattern:
    for n in ('A', 'B', 'R', 'Z', 'V', 'N', 'C', 'W', 'OP', 'CODE', 'ADDR', 'DATA'):
        rx = rx.replace('{' + n + '}', _VAL.format(n=n))
    return re.compile(rx, re.I)


